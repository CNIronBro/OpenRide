    /**
     * 根据 routeKey 和订单状态返回对应路线段坐标数组。
     *
     * @param routeKey  路线标识（A/B/C）
     * @param toPickup  true=接客段，false=行程段
     * @return 坐标数组 double[][]{lat, lng}，routeKey 无效时返回 null
     */
